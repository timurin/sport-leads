def test_snapshot_migration_upgrade_downgrade_upgrade_keeps_manual_locks():
    engine = engine_or_skip()
    schema = "pc044g_" + uuid4().hex
    revision = migration("a7b8c9d0e123_technical_card_route_snapshot.py")
    with engine.connect() as connection:
        transaction = connection.begin()
        try:
            prepare(connection, schema)
            revision.op = Operations(MigrationContext.configure(connection))
            revision.upgrade()
            mapped = connection.execute(text(
                "SELECT tech_operation_id, source_routing_stage_line_id FROM technical_card_stage_results WHERE id = 100"
            )).one()
            assert mapped == (5, 10)
            ambiguous = connection.execute(text(
                "SELECT tech_operation_id, source_routing_stage_line_id FROM technical_card_stage_results WHERE id = 200"
            )).one()
            assert ambiguous == (None, 10)
            created = connection.execute(text(
                "SELECT count(*) FROM technical_card_stage_results WHERE technical_card_id = 3"
            )).scalar()
            assert created == 2
            assert connection.execute(text(
                "SELECT count(*) FROM technical_card_route_edges WHERE technical_card_id = 3"
            )).scalar() == 1
            assert connection.execute(text(
                "SELECT count(*) FROM technical_card_stage_results WHERE technical_card_id = 4"
            )).scalar() == 0
            locks = connection.execute(text(
                "SELECT id, stage_result_id, planning_mode, manual_lock FROM calendar_assignments ORDER BY id"
            )).all()
            assert locks[0] == (1, 100, "manual_adjusted", True)
            assert locks[1][0] == 2 and locks[1][1] is None
            assert locks[1][2:] == ("manual_adjusted", True)
            revision.downgrade()
            assert connection.execute(text(
                "SELECT column_name FROM information_schema.columns "
                "WHERE table_schema = :schema AND table_name = 'calendar_assignments' AND column_name = 'stage_result_id'"
            ), {"schema": schema}).scalar() is None
            revision.upgrade()
            again = connection.execute(text(
                "SELECT stage_result_id, planning_mode, manual_lock FROM calendar_assignments WHERE id = 1"
            )).one()
            assert again == (100, "manual_adjusted", True)
        finally:
            transaction.rollback()
